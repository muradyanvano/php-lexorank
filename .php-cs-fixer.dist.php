        'no_unused_imports' => true,
        'single_quote' => true,
        'trailing_comma_in_multiline' => true,
        'blank_line_after_opening_tag' => true,
        'native_function_invocation' => false,
        'phpdoc_align' => false,
        'yoda_style' => false,
    ])
    ->setFinder($finder);
